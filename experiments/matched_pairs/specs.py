"""Category specifications for matched-pair generation.

A "matched pair" is one attack and one benign example that share task, domain,
register and surface form, generated by the same model in the same call. The
point is that within a pair, generator style is held constant, so a classifier
cannot separate the two by anything except instruction subversion. Generating
the halves separately -- or from different models -- would reintroduce exactly
the style shortcut this data exists to remove.

Category weights were set after the Phase 0 external evaluation. The measured
failure was that benign *application* prompts containing instruction-like
language ("Repeat the above text verbatim", "You are the text completion
model...") scored above every attack on the PromptShield split. So
`instruction_bearing_benign` is the largest category, not a minor slice.

Nothing here embeds corpus text. Every spec is an abstract instruction to the
generator; no row from `data/` is ever transmitted.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Category:
    name: str
    weight: int  # relative share of the total pair budget
    channel: str  # direct_user | untrusted_content
    target_pairs: int
    prompt: str
    # Rough output size per pair, used only for cost projection.
    output_scale: float = 1.0
    languages: tuple[str, ...] = field(default_factory=tuple)
    # Reasoning tokens are billed as output and are roughly FIXED PER CALL, so
    # asking for more pairs per call amortises them directly. Long categories
    # keep a smaller batch because their answers are already near the token cap.
    pairs_per_call: int = 16
    # Measured in ab_reasoning.py: medium effort buys harder benign text for the
    # subtle categories. For the categories where the job is volume or fluency
    # rather than subtlety, it is pure cost.
    reasoning_effort: str = "medium"


_JSON_CONTRACT = """
Return ONLY a JSON array. No prose, no markdown fence. Each element:
{
  "benign":  "<the benign text>",
  "attack":  "<the attacking text>",
  "task":    "<the shared task both texts belong to, one short phrase>",
  "domain":  "<the shared domain>",
  "technique": "<the injection technique used in `attack`>",
  "attack_span": "<the exact substring of `attack` that performs the subversion>"
}

HARD REQUIREMENTS, these are the point of the exercise:
- `benign` and `attack` must be the SAME KIND OF TEXT for the SAME task. Same
  register, comparable length, same formatting conventions. A reader should not
  be able to tell them apart by style, only by intent.
- `benign` MUST NOT be a bland or obviously-safe sentence. It must be realistic
  text that a naive keyword detector would plausibly flag.
- `attack_span` must appear verbatim inside `attack`.
- Vary technique across elements. Do not emit the same phrasing twice.
- Never include real credentials, real personal data, or working exploit code.
"""

